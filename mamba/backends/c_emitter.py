"""
Black Mamba (.bmb) Portable C11 + OpenMP/SIMD (.c) & LLVM IR (.ll) Backends.

Provides:
- `C11Backend`: Emits unboxed, GIL-free C11 with OpenMP/SIMD vectorization pragmas (Nim-style portability, zero Python syntax compromise).
- `LLVMIRBackend`: Emits typed LLVM IR (`.ll`) with `nsw`/`fast` math flags (Mojo/Codon-style LLVM pipeline).
"""

import os
from typing import Dict, List
from ..mir import MIRFunction, MIRInstr, MIRModule


def _c_ident(name: str) -> str:
    if name.startswith("%"):
        return "_t_" + name[1:]
    return name


def _c_type(bmb_type: str) -> str:
    if bmb_type == "f64":
        return "double"
    if bmb_type == "bool":
        return "int64_t"
    if bmb_type == "str":
        return "const char*"
    if bmb_type == "Array[f64]":
        return "double*"
    if bmb_type.startswith("Array[") or bmb_type not in ("i64", "void"):
        return "int64_t*"
    return "int64_t"


class C11Backend:
    """Compiles a MIRModule into portable, auto-vectorizable C11 source code."""

    def __init__(self, mir_module: MIRModule):
        self.mir_module = mir_module

    def emit_c(self) -> str:
        lines = [
            "/* ==========================================================================",
            " * Generated by Black Mamba (.bmb) C11 + OpenMP/SIMD Native Transpiler",
            " * Zero GIL | Unboxed Native Types | Escape-Analyzed Memory | SIMD Ready",
            " * ========================================================================== */",
            "#include <stdint.h>",
            "#include <stdio.h>",
            "#include <stdlib.h>",
            "#include <stdbool.h>",
            "#include <string.h>",
            "#include <math.h>",
            "",
            "static inline int64_t bmb_str_len(const char* s) {",
            "    return (int64_t)strlen(s);",
            "}",
            "",
            "static inline const char* bmb_str_concat(const char* s1, const char* s2) {",
            "    size_t l1 = strlen(s1);",
            "    size_t l2 = strlen(s2);",
            "    char* buf = (char*)malloc(l1 + l2 + 1);",
            "    memcpy(buf, s1, l1);",
            "    memcpy(buf + l1, s2, l2);",
            "    buf[l1 + l2] = '\\0';",
            "    return buf;",
            "}",
            "",
            "static inline const char* bmb_str_slice(const char* s, int64_t start, int64_t stop) {",
            "    int64_t len = (int64_t)strlen(s);",
            "    if (start < 0) start = (len + start > 0) ? (len + start) : 0;",
            "    if (stop < 0) stop = len;",
            "    if (start > len) start = len;",
            "    if (stop < start) stop = start;",
            "    if (stop > len) stop = len;",
            "    int64_t slice_len = stop - start;",
            "    char* buf = (char*)malloc((size_t)slice_len + 1);",
            "    memcpy(buf, s + start, (size_t)slice_len);",
            "    buf[slice_len] = '\\0';",
            "    return buf;",
            "}",
            "",
            "static inline const char* bmb_str_index(const char* s, int64_t idx) {",
            "    int64_t len = (int64_t)strlen(s);",
            "    if (idx < 0) idx += len;",
            "    if (idx < 0 || idx >= len) return \"\";",
            "    char* buf = (char*)malloc(2);",
            "    buf[0] = s[idx];",
            "    buf[1] = '\\0';",
            "    return buf;",
            "}",
            "",
            "static inline const char* bmb_str_from_i64(int64_t v) {",
            "    char* buf = (char*)malloc(32);",
            "    snprintf(buf, 32, \"%lld\", (long long)v);",
            "    return buf;",
            "}",
            "",
            "static inline const char* bmb_str_from_f64(double v) {",
            "    char* buf = (char*)malloc(32);",
            "    snprintf(buf, 32, \"%.6g\", v);",
            "    return buf;",
            "}",
            "",
            "static inline const char* bmb_str_from_bool(int64_t v) {",
            "    return v ? \"True\" : \"False\";",
            "}",
            "",
            "static inline int64_t* __bmb_alloc_i64(int64_t n, int64_t init_val) {",
            "    int64_t* p = (int64_t*)calloc((size_t)(n > 0 ? n : 1), sizeof(int64_t));",
            "    if (init_val != 0) { for (int64_t i = 0; i < n; ++i) p[i] = init_val; }",
            "    return p;",
            "}",
            "",
            "static inline double* __bmb_alloc_f64(int64_t n, double init_val) {",
            "    double* p = (double*)calloc((size_t)(n > 0 ? n : 1), sizeof(double));",
            "    if (init_val != 0.0) { for (int64_t i = 0; i < n; ++i) p[i] = init_val; }",
            "    return p;",
            "}",
            "",
        ]

        # String literal pool
        if self.mir_module.string_pool:
            lines.append("static const char* __bmb_str_pool[] = {")
            for s in self.mir_module.string_pool:
                escaped = s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
                lines.append(f'    "{escaped}",')
            lines.append("};")
            lines.append("")

        # Forward declarations
        for fn in self.mir_module.functions:
            if fn.name in ("main", "__bmb_main__"):
                continue
            ret_c = _c_type(fn.return_type)
            params_c = ", ".join(f"{_c_type(pt)} {_c_ident(pn)}" for pn, pt in fn.params) or "void"
            inline_kw = "static inline " if "inline" in fn.decorators else ""
            lines.append(f"{inline_kw}{ret_c} bmb_{fn.name}({params_c});")
        lines.append("")

        # Function bodies
        for fn in self.mir_module.functions:
            lines.append(self._emit_function(fn))
            lines.append("")

        return "\n".join(lines)

    def write_c(self, output_path: str) -> str:
        c_src = self.emit_c()
        os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(c_src)
        return os.path.abspath(output_path)

    def _emit_function(self, fn: MIRFunction) -> str:
        is_main = fn.name in ("main", "__bmb_main__")
        c_name = "main" if is_main else f"bmb_{fn.name}"
        ret_c = "int" if is_main else _c_type(fn.return_type)
        params_c = "int argc, char** argv" if is_main else (
            ", ".join(f"{_c_type(pt)} {_c_ident(pn)}" for pn, pt in fn.params) or "void"
        )
        inline_kw = "static inline " if ("inline" in fn.decorators and not is_main) else ""

        out = [f"{inline_kw}{ret_c} {c_name}({params_c}) {{"]
        if is_main:
            out.append("    (void)argc; (void)argv;")

        # Declare local variables and temporaries
        param_names = {pn for pn, _ in fn.params}
        declared = set(param_names)
        for vname, vtype in fn.local_types.items():
            if vname not in declared and vname != "%void":
                declared.add(vname)
                out.append(f"    {_c_type(vtype)} {_c_ident(vname)} = 0;")

        for ins in fn.instructions:
            if ins.dst and ins.dst != "%void" and ins.dst not in declared:
                declared.add(ins.dst)
                out.append(f"    {_c_type(ins.val_type)} {_c_ident(ins.dst)} = 0;")

        for ins in fn.instructions:
            op = ins.op
            dst = _c_ident(ins.dst) if ins.dst else ""
            a1 = _c_ident(str(ins.arg1)) if isinstance(ins.arg1, str) else ins.arg1
            a2 = _c_ident(str(ins.arg2)) if isinstance(ins.arg2, str) else ins.arg2

            if op == "LABEL":
                lbl = str(ins.arg1).lstrip(".")
                out.append(f"  {lbl}: ;")
            elif op == "JMP":
                lbl = str(ins.arg1).lstrip(".")
                out.append(f"    goto {lbl};")
            elif op == "JZ":
                lbl = str(ins.arg2).lstrip(".")
                out.append(f"    if (!({a1})) goto {lbl};")
            elif op == "JNZ":
                lbl = str(ins.arg2).lstrip(".")
                out.append(f"    if ({a1}) goto {lbl};")
            elif op == "RET":
                if is_main:
                    out.append(f"    return (int)({a1 if a1 is not None else 0});")
                else:
                    out.append(f"    return {a1 if a1 is not None else 0};")
            elif op == "CONST_I64":
                out.append(f"    {dst} = {int(ins.arg1)}LL;")
            elif op == "CONST_F64":
                out.append(f"    {dst} = {float(ins.arg1)!r};")
            elif op == "CONST_STR":
                out.append(f"    {dst} = __bmb_str_pool[{int(ins.arg1)}];")
            elif op == "MOV":
                if ins.comment == "par_for":
                    out.append("    /* #pragma omp parallel for simd */")
                out.append(f"    {dst} = {a1};")
            elif op in ("I64_TO_F64",):
                out.append(f"    {dst} = (double)({a1});")
            elif op in ("F64_TO_I64",):
                out.append(f"    {dst} = (int64_t)({a1});")
            elif op in ("NEG_I64", "NEG_F64"):
                out.append(f"    {dst} = -({a1});")
            elif op == "NOT_I64":
                out.append(f"    {dst} = ~({a1});")
            elif op == "ABS_I64":
                out.append(f"    {dst} = ({a1}) < 0 ? -({a1}) : ({a1});")
            elif op == "ABS_F64":
                out.append(f"    {dst} = fabs({a1});")
            elif op == "SQRT_F64":
                out.append(f"    {dst} = sqrt({a1});")
            elif op in ("POW_I64", "POW_F64"):
                cast = "(int64_t)" if op == "POW_I64" else ""
                out.append(f"    {dst} = {cast}pow((double)({a1}), (double)({a2}));")
            elif op == "ALLOC_ARR":
                fn_alloc = "__bmb_alloc_f64" if ins.val_type == "Array[f64]" else "__bmb_alloc_i64"
                out.append(f"    {dst} = {fn_alloc}({a1}, {a2});")
            elif op == "LOAD_IDX":
                out.append(f"    {dst} = {a1}[{a2}];")
            elif op == "STORE_IDX":
                out.append(f"    {dst}[{a1}] = {a2};")
            elif op == "PRINT":
                types = [t for t in (ins.comment or "").split(",") if t]
                for idx, (pv, pt) in enumerate(zip(ins.extra, types)):
                    cpv = _c_ident(pv)
                    if idx > 0 and (types[idx - 1] != "str" and pt != "str"):
                        out.append('    printf(" ");')
                    if pt == "f64":
                        out.append(f'    printf("%.6g", (double){cpv});')
                    elif pt == "bool":
                        out.append(f'    printf("%s", ({cpv}) ? "True" : "False");')
                    elif pt == "str":
                        out.append(f'    printf("%s", {cpv});')
                    else:
                        out.append(f'    printf("%lld", (long long){cpv});')
                out.append('    printf("\\n");')
            elif op == "CALL":
                args_c = ", ".join(_c_ident(x) for x in ins.extra)
                if ins.dst and ins.dst != "%void":
                    out.append(f"    {dst} = bmb_{ins.arg1}({args_c});")
                else:
                    out.append(f"    bmb_{ins.arg1}({args_c});")
            elif op in ("PY_CALL_F64", "PY_EVAL_F64"):
                out.append(f"    {dst} = 0.0; /* CPython Host Call */")
            elif op == "ARENA_SAVE":
                out.append(f"    {dst} = 0; /* lexical arena checkpoint */")
            elif op == "ARENA_RESTORE":
                out.append("    /* auto-reclaim lexical arena */")
            elif op == "STR_CONCAT":
                out.append(f"    {dst} = bmb_str_concat({a1}, {a2});")
            elif op == "STR_SLICE":
                stop_arg = _c_ident(str(ins.extra[0])) if ins.extra else "-1"
                out.append(f"    {dst} = bmb_str_slice({a1}, {a2}, {stop_arg});")
            elif op == "STR_INDEX":
                out.append(f"    {dst} = bmb_str_index({a1}, {a2});")
            elif op == "STR_LEN":
                out.append(f"    {dst} = bmb_str_len({a1});")
            elif op == "STR_CMP_EQ":
                out.append(f"    {dst} = (strcmp({a1}, {a2}) == 0);")
            elif op == "STR_CMP_NE":
                out.append(f"    {dst} = (strcmp({a1}, {a2}) != 0);")
            elif op == "STR_FROM_I64":
                out.append(f"    {dst} = bmb_str_from_i64({a1});")
            elif op == "STR_FROM_F64":
                out.append(f"    {dst} = bmb_str_from_f64({a1});")
            elif op == "STR_FROM_BOOL":
                out.append(f"    {dst} = bmb_str_from_bool({a1});")
            elif op == "CLOCK_NS":
                out.append(f"    {dst} = (int64_t)clock();")
            else:
                c_ops = {
                    "ADD_I64": "+", "SUB_I64": "-", "MUL_I64": "*", "DIV_I64": "/", "MOD_I64": "%",
                    "AND_I64": "&", "OR_I64": "|", "XOR_I64": "^", "SHL_I64": "<<", "SHR_I64": ">>",
                    "ADD_F64": "+", "SUB_F64": "-", "MUL_F64": "*", "DIV_F64": "/",
                    "CMP_EQ_I64": "==", "CMP_NE_I64": "!=", "CMP_LT_I64": "<", "CMP_LE_I64": "<=",
                    "CMP_GT_I64": ">", "CMP_GE_I64": ">=",
                    "CMP_EQ_F64": "==", "CMP_NE_F64": "!=", "CMP_LT_F64": "<", "CMP_LE_F64": "<=",
                    "CMP_GT_F64": ">", "CMP_GE_F64": ">=",
                }
                cop = c_ops.get(op, "+")
                out.append(f"    {dst} = ({a1}) {cop} ({a2});")

        out.append("}")
        return "\n".join(out)


class LLVMIRBackend:
    """Emits textual LLVM IR (.ll) from Mamba IR (MIR)."""

    def __init__(self, mir_module: MIRModule):
        self.mir_module = mir_module

    def emit_llvm(self) -> str:
        lines = [
            "; ModuleID = 'black_mamba_module'",
            'target datalayout = "e-m:w-p270:32:32-p271:32:32-p272:64:64-i64:64-f80:128-n8:16:32:64-S128"',
            'target triple = "x86_64-pc-windows-msvc"',
            "",
            "declare i32 @printf(ptr nocapture readonly, ...)",
            "declare ptr @calloc(i64, i64)",
            "@.fmt_i64 = private unnamed_addr constant [6 x i8] c\"%lld\\0A\\00\"",
            "@.fmt_f64 = private unnamed_addr constant [6 x i8] c\"%.6g\\0A\\00\"",
            "",
        ]
        for fn in self.mir_module.functions:
            lines.append(self._emit_llvm_func(fn))
            lines.append("")
        return "\n".join(lines)

    def write_llvm(self, output_path: str) -> str:
        ll_src = self.emit_llvm()
        os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(ll_src)
        return os.path.abspath(output_path)

    def _llvm_type(self, t: str) -> str:
        if t == "f64":
            return "double"
        if t.startswith("Array[") or t == "str":
            return "ptr"
        return "i64"

    def _emit_llvm_func(self, fn: MIRFunction) -> str:
        ret_ll = self._llvm_type(fn.return_type)
        params_ll = ", ".join(f"{self._llvm_type(pt)} %{pn}.arg" for pn, pt in fn.params)
        out = [f"define dso_local {ret_ll} @{fn.name}({params_ll}) #0 {{"]
        out.append("entry:")

        # Alloca slots for locals
        all_vars: Dict[str, str] = dict(fn.local_types)
        for pn, pt in fn.params:
            all_vars[pn] = pt
        for ins in fn.instructions:
            if ins.dst and ins.dst != "%void" and ins.dst not in all_vars:
                all_vars[ins.dst] = ins.val_type

        for vname, vt in all_vars.items():
            if vname == "%void":
                continue
            clean = vname.lstrip("%")
            llt = self._llvm_type(vt)
            out.append(f"  %{clean}.slot = alloca {llt}, align 8")

        for pn, pt in fn.params:
            llt = self._llvm_type(pt)
            out.append(f"  store {llt} %{pn}.arg, ptr %{pn}.slot, align 8")

        out.append("  br label %__tco_entry")

        ssa_id = 0

        def next_ssa() -> str:
            nonlocal ssa_id
            ssa_id += 1
            return f"%r{ssa_id}"

        for ins in fn.instructions:
            op = ins.op
            if op == "LABEL":
                lbl = str(ins.arg1).lstrip(".")
                out.append(f"  br label %{lbl}")
                out.append(f"{lbl}:")
                continue
            if op == "JMP":
                lbl = str(ins.arg1).lstrip(".")
                out.append(f"  br label %{lbl}")
                ssa_lbl = next_ssa().lstrip("%")
                out.append(f"dead_{ssa_lbl}:")
                continue
            if op in ("JZ", "JNZ"):
                c_var = str(ins.arg1).lstrip("%")
                lbl = str(ins.arg2).lstrip(".")
                r_load = next_ssa()
                r_cmp = next_ssa()
                fall_lbl = f"fall_{ssa_id}"
                out.append(f"  {r_load} = load i64, ptr %{c_var}.slot, align 8")
                out.append(f"  {r_cmp} = icmp eq i64 {r_load}, 0")
                if op == "JZ":
                    out.append(f"  br i1 {r_cmp}, label %{lbl}, label %{fall_lbl}")
                else:
                    out.append(f"  br i1 {r_cmp}, label %{fall_lbl}, label %{lbl}")
                out.append(f"{fall_lbl}:")
                continue
            if op == "RET":
                if ins.arg1 is not None and str(ins.arg1) != "%void":
                    rv = str(ins.arg1).lstrip("%")
                    r_load = next_ssa()
                    out.append(f"  {r_load} = load {ret_ll}, ptr %{rv}.slot, align 8")
                    out.append(f"  ret {ret_ll} {r_load}")
                else:
                    zero = "0.0" if ret_ll == "double" else "0"
                    out.append(f"  ret {ret_ll} {zero}")
                dead_lbl = f"ret_cont_{ssa_id}"
                out.append(f"{dead_lbl}:")
                continue
            if op == "CONST_I64" and ins.dst:
                d = ins.dst.lstrip("%")
                out.append(f"  store i64 {int(ins.arg1)}, ptr %{d}.slot, align 8")
                continue
            if op == "CONST_F64" and ins.dst:
                d = ins.dst.lstrip("%")
                out.append(f"  store double {float(ins.arg1):.6e}, ptr %{d}.slot, align 8")
                continue
            if op == "MOV" and ins.dst:
                d = ins.dst.lstrip("%")
                s = str(ins.arg1).lstrip("%")
                llt = self._llvm_type(ins.val_type)
                r = next_ssa()
                out.append(f"  {r} = load {llt}, ptr %{s}.slot, align 8")
                out.append(f"  store {llt} {r}, ptr %{d}.slot, align 8")
                continue

            # Emit comment for other ops
            out.append(f"  ; {ins.format().strip()}")

        zero = "0.0" if ret_ll == "double" else "0"
        out.append(f"  ret {ret_ll} {zero}")
        out.append("}")
        return "\n".join(out)
