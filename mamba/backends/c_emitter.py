def _c_ident(name: str) -> str:
    if name.startswith("%"):
        return "_t_" + name[1:]
    return name


def _c_type(bmb_type: str) -> str:
    if bmb_type == "f64":
        return "double"
    if bmb_type == "bool":
        return "int64_t"
    if bmb_type == "str":
        return "const char*"
    if bmb_type == "Array[f64]":
        return "double*"
    if bmb_type.startswith("Array[") or bmb_type not in ("i64", "void"):
        return "int64_t*"
    return "int64_t"


