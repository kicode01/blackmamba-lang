"""
Black Mamba (bmb) Package Manager — Deterministic Lockfile (`mamba.lock`).
Records exact resolved git commits, paths, and cryptographic integrity hashes.
"""

import os
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

try:
    import tomllib
except ImportError:
    import tomli as tomllib  # type: ignore


@dataclass
class LockedPackage:
    """Exact resolved state of a single dependency in mamba.lock."""
    name: str
    version: str = "0.1.0"
    source: str = "path"  # "git" | "path" | "local"
    url: Optional[str] = None
    ref: Optional[str] = None
    commit: Optional[str] = None
    path: Optional[str] = None
    integrity: str = ""
    dependencies: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        d: Dict[str, Any] = {
            "name": self.name,
            "version": self.version,
            "source": self.source,
        }
        if self.url:
            d["url"] = self.url
        if self.ref:
            d["ref"] = self.ref
        if self.commit:
            d["commit"] = self.commit
        if self.path:
            d["path"] = self.path
        if self.integrity:
            d["integrity"] = self.integrity
        if self.dependencies:
            d["dependencies"] = sorted(self.dependencies)
        return d

    @classmethod
    def from_dict(cls, d: Dict[str, Any]) -> "LockedPackage":
        return cls(
            name=d.get("name", ""),
            version=d.get("version", "0.1.0"),
            source=d.get("source", "path"),
            url=d.get("url"),
            ref=d.get("ref"),
            commit=d.get("commit"),
            path=d.get("path"),
            integrity=d.get("integrity", ""),
            dependencies=d.get("dependencies", []),
        )


@dataclass
class PackageLock:
    """Collection of exact resolved package states."""
    lock_version: int = 1
    packages: Dict[str, LockedPackage] = field(default_factory=dict)

    @classmethod
    def load(cls, file_path: str) -> "PackageLock":
        if not os.path.exists(file_path):
            return cls()
        with open(file_path, "rb") as f:
            data = tomllib.load(f)
        return cls.from_dict(data)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "PackageLock":
        lock_ver = data.get("lock-version", 1)
        raw_pkgs = data.get("package", [])
        packages: Dict[str, LockedPackage] = {}
        for p in raw_pkgs:
            lp = LockedPackage.from_dict(p)
            packages[lp.name] = lp
        return cls(lock_version=lock_ver, packages=packages)

    def to_toml(self) -> str:
        def _q(val: Any) -> str:
            s = str(val).replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
            return f'"{s}"'

        lines = [
            "# This file is automatically generated by Black Mamba package manager (bmb pkg).",
            "# Manual edits will be overwritten. Deterministic reproducibility lockfile.",
            "",
            f"lock-version = {self.lock_version}",
            "",
        ]

        for pname in sorted(self.packages.keys()):
            pkg = self.packages[pname]
            lines.append("[[package]]")
            lines.append(f"name = {_q(pkg.name)}")
            lines.append(f"version = {_q(pkg.version)}")
            lines.append(f"source = {_q(pkg.source)}")
            if pkg.url:
                lines.append(f"url = {_q(pkg.url)}")
            if pkg.ref:
                lines.append(f"ref = {_q(pkg.ref)}")
            if pkg.commit:
                lines.append(f"commit = {_q(pkg.commit)}")
            if pkg.path:
                lines.append(f"path = {_q(pkg.path)}")
            if pkg.integrity:
                lines.append(f"integrity = {_q(pkg.integrity)}")
            if pkg.dependencies:
                dep_str = ", ".join(_q(d) for d in sorted(pkg.dependencies))
                lines.append(f"dependencies = [{dep_str}]")
            else:
                lines.append("dependencies = []")
            lines.append("")

        return "\n".join(lines)

    def save(self, file_path: str) -> None:
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(self.to_toml())
